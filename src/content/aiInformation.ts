function listItems(items: string[]) {
  return items.map((item) => `<li>${item}</li>`).join('');
}

function definitionCards(items: Array<{ label: string; copy: string }>) {
  return items.map((item) => `<h3>${item.label}</h3><p>${item.copy}</p>`).join('\n        ');
}

