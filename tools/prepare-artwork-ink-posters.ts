import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { dirname, join } from 'node:path'
import sharp from 'sharp'
import { inkArtworkPixels, type ArtworkInkColor } from '../src/personal/editorial/artwork-ink-pixels.ts'

// Preserve the authored posters; derive the public document's current palette.
const sourceDirectory = 'public/images/generative-art'
const outputDirectory = join(sourceDirectory, 'ink')
const paletteSource = await readFile('src/personal/personal.css', 'utf8')
const hex = paletteSource.match(/--ink:\s*#([\da-f]{6})/i)?.[1]
if (!hex) throw new Error('The public cover palette must have a six-digit ink token.')
const ink = [0, 2, 4].map(at => parseInt(hex.slice(at, at + 2), 16)) as unknown as ArtworkInkColor
const originals = (await readdir(sourceDirectory)).filter(name => /^yuru-\d+\.webp$/.test(name)).sort()
if (!originals.length) throw new Error('Original artwork posters are missing.')
await mkdir(outputDirectory, { recursive: true })

const manifest: Record<string, string> = {}
let sourceBytes = 0, inkBytes = 0
for (const filename of originals) {
  const original = await readFile(join(sourceDirectory, filename))
  const { data, info } = await sharp(original).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  if (info.width !== 400 || info.height !== 400 || info.channels !== 4) throw new Error(`Unexpected original poster geometry: ${filename}`)
  const pixels = new Uint8ClampedArray(data.buffer, data.byteOffset, data.byteLength)
  inkArtworkPixels(pixels, ink)
  const encoded = await sharp(Buffer.from(pixels), { raw: { width: info.width, height: info.height, channels: 4 } }).webp({ lossless: true, effort: 6 }).toBuffer()
  const id = filename.slice(0, -5)
  const version = createHash('sha256').update(encoded).digest('hex').slice(0, 12)
  const outputName = `${id}-${version}.webp`
  await writeFile(join(outputDirectory, outputName), encoded)
  manifest[id] = `/images/generative-art/ink/${outputName}`
  sourceBytes += original.length; inkBytes += encoded.length
}

const generated = 'src/personal/editorial/artwork-ink-posters.generated.ts'
await mkdir(dirname(generated), { recursive: true })
await writeFile(generated, `// Generated by tools/prepare-artwork-ink-posters.ts; original artwork is untouched.\nexport const ARTWORK_POSTER_INK = ${JSON.stringify(ink)} as const\nexport const ARTWORK_INK_POSTERS: Readonly<Record<string, string>> = ${JSON.stringify(manifest, null, 2)}\n`)
console.log(JSON.stringify({ generated: originals.length, ink, sourceBytes, inkBytes, manifest: generated }))
