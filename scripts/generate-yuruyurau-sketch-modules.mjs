import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(repositoryRoot, 'scripts/data/yuruyurau-sketches.json');
const outputDirectory = path.join(repositoryRoot, 'src/art/generative/sketches');
const loadersPath = path.join(repositoryRoot, 'src/art/generative/generatedSketchLoaders.ts');
const records = JSON.parse(await readFile(sourcePath, 'utf8'));

const runtimePrelude = `  const PI = instance.PI;
  const abs = instance.abs.bind(instance);
  const atan2 = instance.atan2.bind(instance);
  const background = instance.background.bind(instance);
  const circle = instance.circle.bind(instance);
  const clear = instance.clear.bind(instance);
  const cos = instance.cos.bind(instance);
  const fill = instance.fill.bind(instance);
  const get = instance.get.bind(instance);
  const image = instance.image.bind(instance);
  const mag = instance.mag.bind(instance);
  const noStroke = instance.noStroke.bind(instance);
  const point = instance.point.bind(instance);
  const rotate = instance.rotate.bind(instance);
  const sin = instance.sin.bind(instance);
  const stroke = instance.stroke.bind(instance);
  const strokeWeight = instance.strokeWeight.bind(instance);
  const translate = instance.translate.bind(instance);
  const createCanvas = (...args) => {
    const renderer = instance.createCanvas(...args);
    instance.pixelDensity(Math.min(window.devicePixelRatio || 1, 2));
    return renderer;
  };
  let a, b, c, d, e, f, i, k, m, n, o, p, q, s, t, u, w, x, y, z;
`;

function indent(value, spaces = 2) {
  const padding = ' '.repeat(spaces);
  return value.split('\n').map((line) => `${padding}${line}`).join('\n');
}

function portSource(code) {
  return code.replace(/\bdraw\s*=/g, 'instance.draw =');
}

await mkdir(outputDirectory, { recursive: true });

for (const record of records) {
  const moduleSource = `// @ts-nocheck -- preserves the artist's compact mathematical notation verbatim.
import type { P5SketchFactory } from '../types';

/**
 * Instance-mode port of ${record.sourceUrl}
 * Formula and timing are preserved; only p5 globals are bound to this instance.
 */
const sketch: P5SketchFactory = (instance) => {
${runtimePrelude}${indent(portSource(record.code))};
};

export default sketch;
`;
  await writeFile(path.join(outputDirectory, `${record.id}.ts`), moduleSource);
}

const loaders = records
  .map((record) => `  '${record.id}': () => import('./sketches/${record.id}'),`)
  .join('\n');

await writeFile(loadersPath, `// Generated by scripts/generate-yuruyurau-sketch-modules.mjs.
import type { P5SketchLoader } from './types';

export const GENERATED_SKETCH_LOADERS = {
${loaders}
} satisfies Record<string, P5SketchLoader>;
`);

console.log(`Generated ${records.length} reviewed instance-mode sketch modules.`);
